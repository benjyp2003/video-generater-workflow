"""Generate storyboard.yaml from script.md (+ optional storyboard.overrides.yaml).

Usage: python3 -m tools.storyboard videos/<id>

storyboard.yaml is GENERATED (gitignored). Put hand edits in
storyboard.overrides.yaml (committed), keyed by scene id, e.g.:

  s02:
    motion: zoom          # none | zoom   (images only)
    pad_after_s: 1.0
  s05:
    visuals: [{type: screen, name: browser-demo}]

Visual name -> file lookup (first match wins), in media/visuals/ then media/raw/:
  diagram|slide|image: <name>.png|.jpg
  terminal|screen:     <name>.mp4|.mov|.mkv  (falls back to .png)
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

from tools.scriptdoc import load_script, load_yaml

RESOLUTIONS = {"short": "1080x1920"}
DEFAULT_RES = "1920x1080"
IMAGE_EXT = (".png", ".jpg", ".jpeg")
VIDEO_EXT = (".mp4", ".mov", ".mkv")
SEARCH_DIRS = ("media/visuals", "media/raw")


def resolve_visual(video_dir: Path, vtype: str, name: str) -> str | None:
    exts = VIDEO_EXT + IMAGE_EXT if vtype in ("terminal", "screen") else IMAGE_EXT
    for d in SEARCH_DIRS:
        for ext in exts:
            p = video_dir / d / f"{name}{ext}"
            if p.exists():
                return str(p.relative_to(video_dir))
    return None


def build(video_dir: Path) -> dict:
    manifest = load_yaml(video_dir / "video.yaml")
    overrides = load_yaml(video_dir / "storyboard.overrides.yaml")
    script = load_script(video_dir)
    scenes = []
    for s in script.scenes:
        ov = overrides.get(s.id) or {}
        visuals = ov.get("visuals") or [{"type": v.type, "name": v.name} for v in s.visuals]
        resolved = []
        for v in visuals:
            resolved.append({**v, "src": v.get("src") or resolve_visual(video_dir, v["type"], v["name"])})
        scenes.append({
            "id": s.id,
            "title": s.title,
            "narration": f"media/audio/{s.id}.wav" if s.narration else None,
            "visuals": resolved,
            "motion": ov.get("motion", "none"),
            "pad_after_s": float(ov.get("pad_after_s", 0.4)),
            "min_duration_s": float(ov.get("min_duration_s", 2.0)),
        })
    return {
        "schema_version": 1,
        "generated_from": "script.md + storyboard.overrides.yaml",
        "resolution": RESOLUTIONS.get(manifest.get("format"), DEFAULT_RES),
        "fps": 30,
        "scenes": scenes,
    }


def write(video_dir: Path) -> dict:
    sb = build(video_dir)
    out = video_dir / "storyboard.yaml"
    out.write_text("# GENERATED by tools/storyboard.py — edit storyboard.overrides.yaml instead\n"
                   + yaml.safe_dump(sb, sort_keys=False))
    return sb


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__)
        return 2
    sb = write(Path(argv[1]))
    missing = [f"{s['id']}: {v['type']}:{v['name']}" for s in sb["scenes"]
               for v in s["visuals"] if not v["src"]]
    print(f"storyboard: {len(sb['scenes'])} scenes, {len(missing)} missing visual(s)")
    for m in missing:
        print(f"  missing {m}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
